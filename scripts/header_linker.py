#!/usr/bin/env python3
r"""
header_linker.py - Multi-File Header Dependency Linker and Python Package Generator.

Features:
- Scans .h, .hpp, .c, .cpp files in a project directory
- Extracts local #include "..." dependency graph (DAG)
- Computes topological sort order for transpilation
- Detects circular include cycles
- Generates Python package structure with __init__.py and relative imports
"""

from __future__ import annotations
import os
import re
from pathlib import Path
from typing import Dict, List, Set, Tuple, Optional


class CppProjectLinker:
    def __init__(self, project_dir: str | Path):
        self.project_dir = Path(project_dir)
        self.files: Dict[str, Path] = {}
        self.dependencies: Dict[str, Set[str]] = {}
        self.system_includes: Dict[str, Set[str]] = {}

    def scan(self):
        r"""Scan directory for C/C++ source and header files."""
        for ext in ("*.h", "*.hpp", "*.c", "*.cpp", "*.cc", "*.cxx"):
            for p in self.project_dir.glob(ext):
                self.files[p.name] = p
                self.dependencies[p.name] = set()
                self.system_includes[p.name] = set()

        # Parse includes
        include_pat = re.compile(r'^\s*#include\s+([<"])([^>"]+)([>"])')
        for name, path in self.files.items():
            text = path.read_text(encoding="utf-8", errors="ignore")
            for line in text.splitlines():
                m = include_pat.match(line.strip())
                if m:
                    kind = m.group(1)
                    inc_target = Path(m.group(2)).name
                    if kind == '"' and inc_target in self.files:
                        self.dependencies[name].add(inc_target)
                    else:
                        self.system_includes[name].add(m.group(2))

    def topological_sort(self) -> List[str]:
        r"""Compute topological order of files (headers first, then implementations)."""
        visited: Dict[str, int] = {f: 0 for f in self.files}  # 0: unvisited, 1: visiting, 2: visited
        order: List[str] = []

        def dfs(node: str):
            visited[node] = 1
            for neighbor in sorted(self.dependencies.get(node, [])):
                if visited[neighbor] == 1:
                    # Circular dependency detected, break gracefully
                    continue
                elif visited[neighbor] == 0:
                    dfs(neighbor)
            visited[node] = 2
            order.append(node)

        for f in sorted(self.files.keys()):
            if visited[f] == 0:
                dfs(f)

        return order

    def generate_init_py(self, sorted_files: List[str]) -> str:
        r"""Generate __init__.py for the modern Python package."""
        lines = [
            "# ============================================================================",
            "# Python Package Generated by cppBridge Multi-File Linker",
            "# ============================================================================",
            "from __future__ import annotations",
            ""
        ]

        for fname in sorted_files:
            stem = Path(fname).stem
            lines.append(f"from .{stem} import *")

        lines.append("\n__all__ = [")
        for fname in sorted_files:
            stem = Path(fname).stem
            lines.append(f'    "{stem}",')
        lines.append("]\n")
        return "\n".join(lines)


def run_self_test() -> bool:
    r"""Test topological sorting and dependency analysis."""
    print("Running header_linker self-test...")
    import tempfile

    with tempfile.TemporaryDirectory() as tmpdir:
        td = Path(tmpdir)
        # Create mock project
        (td / "types.h").write_text("struct Vector3 { double x, y, z; };")
        (td / "physics.h").write_text('#include "types.h"\nvoid force();')
        (td / "solver.cpp").write_text('#include "physics.h"\n#include "types.h"\nint main(){}')

        linker = CppProjectLinker(td)
        linker.scan()
        order = linker.topological_sort()

        # types.h must precede physics.h, and physics.h must precede solver.cpp
        assert order.index("types.h") < order.index("physics.h"), "types.h should precede physics.h"
        assert order.index("physics.h") < order.index("solver.cpp"), "physics.h should precede solver.cpp"

        init_code = linker.generate_init_py(order)
        assert "from .types import *" in init_code
        assert "from .physics import *" in init_code
        assert "from .solver import *" in init_code

    print("header_linker self-test passed successfully!")
    return True


if __name__ == "__main__":
    run_self_test()
