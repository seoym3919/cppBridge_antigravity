#!/usr/bin/env python3
r"""
pybind11_generator.py - Generates Turnkey pybind11 Wrappers and setup.py for C/C++ Kernels.

Allows C/C++ scientific functions to be directly compiled into native Python extensions
with zero-copy NumPy array integration (py::array_t<double>).
"""

from __future__ import annotations
import os
import re
from typing import List, Dict, Any, Tuple


class CppFunctionSignature:
    def __init__(self, name: str, return_type: str, raw_params: str):
        self.name = name.strip()
        self.return_type = return_type.strip()
        self.params: List[Dict[str, str]] = []
        self._parse_params(raw_params)

    def _parse_params(self, raw_params: str):
        if not raw_params.strip():
            return
        parts = [p.strip() for p in raw_params.split(',')]
        for p in parts:
            # e.g.: double* pos, const double* vel, int n, double dt
            is_const = "const" in p
            is_ptr = "*" in p or "&" in p
            clean = re.sub(r'\bconst\b', '', p).replace('*', '').replace('&', '').strip()
            tokens = clean.split()
            if len(tokens) >= 2:
                param_type = " ".join(tokens[:-1])
                param_name = tokens[-1]
            elif len(tokens) == 1:
                param_type = tokens[0]
                param_name = f"arg"
            else:
                param_type = "double"
                param_name = "arg"

            self.params.append({
                "name": param_name,
                "type": param_type,
                "is_ptr": is_ptr,
                "is_const": is_const,
                "raw": p
            })


def extract_cpp_signatures(header_text: str) -> List[CppFunctionSignature]:
    r"""Extract function prototypes from header or source file."""
    signatures = []
    # Match return_type func_name(params);
    proto_pat = re.compile(
        r'^\s*(?:extern\s+"C"\s+)?([A-Za-z0-9_:*&<>\s]+?)\s+([A-Za-z0-9_]+)\s*\(([^)]*)\)\s*(?:;|(?=\{))',
        re.MULTILINE
    )
    for m in proto_pat.finditer(header_text):
        ret_t = m.group(1).strip()
        fname = m.group(2).strip()
        raw_p = m.group(3).strip()
        if fname in ("if", "for", "while", "switch", "catch"):
            continue
        signatures.append(CppFunctionSignature(fname, ret_t, raw_p))
    return signatures


def generate_pybind11_binding_file(
    module_name: str,
    header_name: str,
    functions: List[CppFunctionSignature]
) -> str:
    r"""Generate complete C++ pybind11 wrapper file."""
    lines = [
        "// ============================================================================",
        "// Automated pybind11 Wrapper generated by cppBridge",
        "// ============================================================================\n",
        "#include <pybind11/pybind11.h>",
        "#include <pybind11/numpy.h>",
        "#include <pybind11/stl.h>",
        f'#include "{header_name}"',
        "",
        "namespace py = pybind11;",
        "",
        f"PYBIND11_MODULE({module_name}, m) {{",
        f'    m.doc() = "Native C++ accelerated bindings generated by cppBridge";',
        ""
    ]

    for fn in functions:
        has_array = any(p["is_ptr"] and p["type"] in ("double", "float", "int") for p in fn.params)
        if not has_array:
            # Simple direct binding
            lines.append(f'    m.def("{fn.name}", &{fn.name}, "Native binding for {fn.name}");')
        else:
            # NumPy array lambda wrapper
            wrapper_args = []
            call_args = []
            unpack_lines = []

            for p in fn.params:
                pname = p["name"]
                if p["is_ptr"] and p["type"] in ("double", "float", "int"):
                    wrapper_args.append(f"py::array_t<{p['type']}> {pname}")
                    if p["is_const"]:
                        unpack_lines.append(f"        auto r_{pname} = {pname}.unchecked<1>();")
                        call_args.append(f"r_{pname}.data()")
                    else:
                        unpack_lines.append(f"        auto r_{pname} = {pname}.mutable_unchecked<1>();")
                        call_args.append(f"r_{pname}.mutable_data()")
                else:
                    wrapper_args.append(f"{p['type']} {pname}")
                    call_args.append(pname)

            lines.append(f'    m.def("{fn.name}", []({", ".join(wrapper_args)}) {{')
            for ul in unpack_lines:
                lines.append(ul)
            ret_prefix = "" if fn.return_type == "void" else "return "
            lines.append(f"        {ret_prefix}{fn.name}({', '.join(call_args)});")
            lines.append(f'    }}, "NumPy-accelerated binding for {fn.name}");')
            lines.append("")

    lines.append("}\n")
    return "\n".join(lines)


def generate_pybind11_module(code_text: str, module_name: str, header_name: str = "") -> str:
    r"""Generate complete pybind11 module from C/C++ code."""
    funcs = extract_cpp_signatures(code_text)
    h_name = header_name if header_name else f"{module_name}.h"
    return generate_pybind11_binding_file(module_name, h_name, funcs)


def generate_setup_py(module_name: str, source_files: List[str] | str) -> str:
    r"""Generate turnkey setup.py for compiling the pybind11 extension."""
    if isinstance(source_files, str):
        sources = [source_files]
    else:
        sources = source_files
    src_list = ", ".join(f'"{s}"' for s in sources)
    return f"""from setuptools import setup, Extension
from pybind11.setup_helpers import Pybind11Extension, build_ext

ext_modules = [
    Pybind11Extension(
        "{module_name}",
        [{src_list}],
        extra_compile_args=["-O3", "-march=native", "-std=c++20"],
    ),
]

setup(
    name="{module_name}",
    version="0.1.0",
    author="cppBridge Automated Generator",
    description="Accelerated C++ extension compiled with pybind11",
    ext_modules=ext_modules,
    cmdclass={{"build_ext": build_ext}},
)
"""


if __name__ == "__main__":
    header_sample = """
    void nbody_step(double* pos, double* vel, int n, double dt);
    double compute_energy(const double* pos, const double* vel, int n);
    int find_closest(const double* pos, int n, double target_x);
    """
    funcs = extract_cpp_signatures(header_sample)
    print(f"[pybind11_generator] Extracted {len(funcs)} functions:")
    for f in funcs:
        print(f"  {f.return_type} {f.name}(...) with {len(f.params)} parameters")

    print("\nGenerated pybind11 Binding File:")
    print(generate_pybind11_binding_file("nbody_native", "nbody.h", funcs))
