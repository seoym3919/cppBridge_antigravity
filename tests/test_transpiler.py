import unittest
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"
sys.path.insert(0, str(SCRIPTS))

from cpp_to_python_transpiler import convert_cpp_expression_to_python, FunctionContext, tokenize, transpile_cpp_to_python  # noqa: E402
from pointer_analyzer import decompile_pointer_arithmetic  # noqa: E402

_COUNTER = [0]


def load(src):
    """Transpile C source and exec the resulting Python; returns its namespace."""
    code = transpile_cpp_to_python(src)
    _COUNTER[0] += 1
    mod = types.ModuleType(f"transpiled_{_COUNTER[0]}")
    sys.modules[mod.__name__] = mod
    exec(compile(code, "<transpiled>", "exec"), mod.__dict__)  # noqa: S102 - generated by the code under test
    return mod.__dict__


class PointerArithmeticTests(unittest.TestCase):
    def test_multiplication_is_not_a_dereference(self):
        # regression: `a[j] * (i + 1)` used to become `a[j] i[1]`
        self.assertEqual(decompile_pointer_arithmetic("a[j] * (i + 1)"), "a[j] * (i + 1)")
        self.assertEqual(decompile_pointer_arithmetic("x = n * (m + 2)"), "x = n * (m + 2)")

    def test_unary_dereference_still_works(self):
        self.assertEqual(decompile_pointer_arithmetic("*(pos + 5)"), "pos[5]")
        self.assertEqual(decompile_pointer_arithmetic("x = *(pos + 5)").replace("  ", " "), "x = pos[5]")
        self.assertEqual(decompile_pointer_arithmetic("*ptr"), "ptr[0]")
        self.assertEqual(decompile_pointer_arithmetic("&vel[i]"), "vel[i:]")


class TokenizerTests(unittest.TestCase):
    def test_splits_statements_and_blocks(self):
        toks = tokenize("int f(int n) { int k = 0; for (int i = 0; i < n; i++) { k += i; } return k; }")
        kinds = [k for k, _ in toks]
        self.assertEqual(kinds, ["head", "open", "stmt", "head", "open", "stmt", "close", "stmt", "close"])
        self.assertEqual(toks[3][1], "for (int i = 0; i < n; i++)")      # semicolons inside () are not splits

    def test_comments_and_strings(self):
        toks = tokenize('x = 1; // note; with semicolon\n/* a; b */ s = "a;b{";\n')
        self.assertEqual([t for _, t in toks], ["x = 1", 's = "a;b{"'])

    def test_initializer_list_stays_one_statement(self):
        toks = tokenize("double a[3] = {1.0, 2.0, 3.0};")
        self.assertEqual(toks, [("stmt", "double a[3] = {1.0, 2.0, 3.0}")])


class ExpressionTests(unittest.TestCase):
    def conv(self, text, ints=()):
        ctx = FunctionContext()
        ctx.int_names.update(ints)
        return convert_cpp_expression_to_python(text, ctx)[0]

    def test_logical_and_casts(self):
        self.assertEqual(self.conv("a && !b || c"), "a and not b or c")
        self.assertEqual(self.conv("(double)n / m"), "float(n) / m")
        self.assertEqual(self.conv("(int)(x * 2)"), "int(x * 2)")

    def test_integer_division_only_for_int_operands(self):
        self.assertEqual(self.conv("n / 2", ints=("n",)), "int(n / 2)")
        self.assertEqual(self.conv("x / 2"), "x / 2")
        self.assertEqual(self.conv("n / 2.0", ints=("n",)), "n / 2.0")

    def test_ternary(self):
        self.assertEqual(self.conv("a > b ? a : b"), "(a if a > b else b)")
        self.assertEqual(self.conv("r = c ? 1 : d ? 2 : 3"), "r = (1 if c else (2 if d else 3))")

    def test_math_names_and_constants(self):
        self.assertEqual(self.conv("fabs(x) + floor(y)"), "abs(x) + math.floor(y)")
        self.assertEqual(self.conv("M_PI * r"), "math.pi * r")


C_PROGRAM = r'''
#include <math.h>
#define NMAX 8
/* block comment
   spanning lines */
static const double SCALE = 2.0;

int half(int n) { return n / 2; }
double ratio(int a, int b) { return a / b; }
double mean_ratio(int a, int b) { return (double)a / b; }
int maxi(int a, int b) { return a > b ? a : b; }

double sum_to(int n) {
    double s = 0.0;
    for (int i = 1; i <= n; i++) s += i;       // brace-less body
    return s;
}
int countdown(int n) {
    int k = 0;
    for (int i = n; i > 0; i -= 2) { k++; }
    return k;
}
int collatz(int n) {
    int steps = 0;
    while (n != 1) {
        if (n % 2 == 0) n = n / 2;
        else n = 3 * n + 1;
        steps++;
    }
    return steps;
}
int classify(double x) {
    if (x < 0) {
        return -1;
    } else if (x == 0) {
        return 0;
    } else {
        return 1;
    }
}
int dowhile(int n) {
    int k = 0;
    do {
        k += 2;
    } while (k < n);
    return k;
}
double arrays(int n) {
    double a[3] = {1.0, 2.0, 3.0};
    double m[2][3];
    int cnt[4];
    double *v = (double*)malloc(n * sizeof(double));
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 3; j++)
            m[i][j] = a[j] * (i + 1);
    for (int i = 0; i < n; i++) v[i] = i * 0.5;
    cnt[0] = 7;
    double r = m[1][2] + cnt[0] + v[n - 1];
    free(v);
    return r;
}
void inc(int &k) { k++; }
void scale_all(double *x, int n) {
    for (int i = 0; i < n; ++i) x[i] *= SCALE;
}
double consts(double x) { return fabs(x) + floor(x) + fmod(7.5, 2.0) + M_PI; }
int divassign(int n) { n /= 2; return n; }
void axpy_norm(int n, double alpha, const double *x, double *y, double *out) {
    double s = 0.0;
    for (int i = 0; i < n; ++i) {
        y[i] = y[i] + alpha * x[i];
        s += y[i] * y[i];
    }
    *out = sqrt(s);
}
void report(int n, double v) { printf("n=%d v=%.2f\n", n, v); }
int jump(int n) {
    if (n > 0) goto done;
    n = 5;
done:
    return n;
}
int sw(int n) {
    switch (n) {
        case 1: return 10;
        default: return 0;
    }
}
'''


class TranspiledNumericsTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.ns = load(C_PROGRAM)

    def test_integer_division_truncates_toward_zero(self):
        self.assertEqual(self.ns["half"](7), 3)
        self.assertEqual(self.ns["half"](-7), -3)             # C: -3 (Python // would give -4)
        self.assertEqual(self.ns["ratio"](7, 2), 3)           # int / int, then widened to double
        self.assertEqual(self.ns["mean_ratio"](7, 2), 3.5)    # (double)a / b
        self.assertEqual(self.ns["divassign"](-7), -3)        # n /= 2

    def test_ternary_and_loops(self):
        self.assertEqual(self.ns["maxi"](3, 9), 9)
        self.assertEqual(self.ns["sum_to"](10), 55.0)         # 1+...+10
        self.assertEqual(self.ns["countdown"](7), 4)          # 7,5,3,1
        self.assertEqual(self.ns["collatz"](27), 111)         # known Collatz stopping time of 27
        self.assertEqual(self.ns["dowhile"](7), 8)            # body runs until k >= 7: 2,4,6,8

    def test_if_else_if_else_chain(self):
        classify = self.ns["classify"]
        self.assertEqual([classify(-2.0), classify(0.0), classify(3.0)], [-1, 0, 1])

    def test_arrays_malloc_and_nested_loops(self):
        # m[1][2] = a[2]*2 = 6 ; cnt[0] = 7 ; v[3] = 1.5
        self.assertEqual(self.ns["arrays"](4), 6.0 + 7 + 1.5)

    def test_by_reference_scalar_becomes_one_element_array(self):
        k = np.array([5])
        self.ns["inc"](k)
        self.assertEqual(int(k[0]), 6)

    def test_global_constant_and_in_place_arrays(self):
        x = np.array([1.0, 2.0])
        self.ns["scale_all"](x, 2)
        np.testing.assert_array_equal(x, [2.0, 4.0])

    def test_math_functions(self):
        expected = abs(-2.5) + np.floor(-2.5) + np.fmod(7.5, 2.0) + np.pi
        self.assertAlmostEqual(self.ns["consts"](-2.5), expected, places=14)

    def test_pointer_output_matches_numpy(self):
        rng = np.random.default_rng(7)                        # fixed seed
        x, y = rng.random(20), rng.random(20)
        y_ref = y + 0.3 * x
        out = np.zeros(1)
        self.ns["axpy_norm"](20, 0.3, x, y, out)
        np.testing.assert_allclose(y, y_ref, rtol=1e-15)
        self.assertAlmostEqual(out[0], np.linalg.norm(y_ref), places=13)

    def test_printf(self):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            self.ns["report"](3, 2.5)
        self.assertEqual(buf.getvalue().strip(), "n=3 v=2.50")

    def test_unsupported_constructs_fail_loudly_but_translation_succeeds(self):
        with self.assertRaises(NotImplementedError):
            self.ns["jump"](1)                                # goto taken
        self.assertEqual(self.ns["jump"](-1), 5)              # the non-goto path still works
        with self.assertRaises(NotImplementedError):
            self.ns["sw"](1)                                  # switch


class StructureTests(unittest.TestCase):
    def test_openmp_parallel_for_becomes_prange(self):
        code = transpile_cpp_to_python(
            "void f(double *x, int n) {\n#pragma omp parallel for\nfor (int i = 0; i < n; ++i) x[i] = 2 * x[i];\n}\n")
        self.assertIn("from numba import njit, prange", code)
        self.assertIn("@njit(parallel=True)\ndef f(", code)
        self.assertIn("for i in prange(int(n)):", code)
        compile(code, "<omp>", "exec")

    def test_struct_becomes_dataclass_and_instances(self):
        code = transpile_cpp_to_python(
            "typedef struct { double x, y; } P;\ndouble norm2(void) { P p; p.x = 3.0; p.y = 4.0; return p.x*p.x + p.y*p.y; }\n")
        mod = types.ModuleType("m2")
        sys.modules["m2"] = mod
        exec(compile(code, "<s>", "exec"), mod.__dict__)
        self.assertEqual(mod.norm2(), 25.0)

    def test_empty_blocks_get_pass(self):
        code = transpile_cpp_to_python("void f(int n) { if (n > 0) { } else { } }\n")
        compile(code, "<e>", "exec")
        self.assertEqual(code.count("pass"), 2)

    def test_shipped_example_parses_and_matches_independent_leapfrog(self):
        code = transpile_cpp_to_python((ROOT / "examples" / "nbody_simulation.c").read_text())
        mod = types.ModuleType("nbody")
        sys.modules["nbody"] = mod
        exec(compile(code, "<nbody>", "exec"), mod.__dict__)
        rng = np.random.default_rng(11)
        n, dt, steps, soft = 4, 0.01, 5, 0.05
        pos = rng.random(3 * n)
        vel = rng.random(3 * n) * 0.1
        mass = rng.random(n) + 0.5
        p0, v0 = pos.copy(), vel.copy()
        with contextlib.redirect_stdout(io.StringIO()):
            mod.leapfrog_integrate(pos, vel, mass, n, dt, steps, soft)
        # independent implementation of the same kick-then-drift scheme
        p, v = p0.reshape(n, 3).copy(), v0.reshape(n, 3).copy()
        for _ in range(steps):
            d = p[None, :, :] - p[:, None, :]
            r2 = (d ** 2).sum(-1) + soft ** 2
            w = mass[None, :] / r2 ** 1.5
            np.fill_diagonal(w, 0.0)
            a = (w[:, :, None] * d).sum(1)
            v = v + a * dt
            p = p + v * dt
        np.testing.assert_allclose(pos.reshape(n, 3), p, rtol=1e-12)    # observed ~1e-16
        np.testing.assert_allclose(vel.reshape(n, 3), v, rtol=1e-12)


class CliTests(unittest.TestCase):
    CLI = str(SCRIPTS / "cpp_bridge_cli.py")

    def run_cli(self, *args, cwd=None):
        return subprocess.run([sys.executable, "-B", self.CLI, *args], capture_output=True, text=True, cwd=cwd)

    def test_self_test_passes(self):
        res = self.run_cli("--self-test")
        self.assertEqual(res.returncode, 0, res.stderr[-500:])

    def test_single_file_and_untranslated_note(self):
        with tempfile.TemporaryDirectory() as d:
            src = Path(d) / "k.c"
            src.write_text("int f(int n) { switch (n) { case 1: return 1; } return 0; }\n")
            res = self.run_cli("-i", str(src), "-o", str(Path(d) / "k.py"))
            self.assertEqual(res.returncode, 0, res.stderr)
            self.assertIn("not translated", res.stderr)
            compile((Path(d) / "k.py").read_text(), "k.py", "exec")

    def test_directory_mode(self):
        with tempfile.TemporaryDirectory() as d:
            proj = Path(d) / "proj"
            proj.mkdir()
            (proj / "k.c").write_text("double twice(double x) { return 2.0 * x; }\n")
            out = Path(d) / "out"
            res = self.run_cli(str(proj), "--out-dir", str(out), "--report", str(Path(d) / "r.md"))
            self.assertEqual(res.returncode, 0, res.stderr)
            self.assertTrue((out / "k.py").exists())
            self.assertTrue((Path(d) / "r.md").exists())

    def test_documented_flags_exist(self):
        """Every --flag shown next to cpp_bridge_cli.py in rules/skills/agents/README is a real option."""
        helptext = self.run_cli("--help").stdout
        real = set(re.findall(r"--[a-z][a-z0-9-]*", helptext))
        docs = list((ROOT / "rules").glob("*.md")) + [ROOT / "README.md"]
        docs += list((ROOT / "skills").glob("*/SKILL.md")) + list((ROOT / "agents").glob("*.md"))
        for doc in docs:
            for line in doc.read_text().splitlines():
                if "cpp_bridge_cli.py" in line:
                    for flag in re.findall(r"(?<![\w-])--[a-z][a-z0-9-]*", line):
                        self.assertIn(flag, real, f"{doc.name}: {line.strip()}")


class AllScriptsDocFlagsTests(unittest.TestCase):
    """Every --flag written after `scripts/<name>.py` in rules/skills/agents/README must exist in that script."""

    def test_documented_flags_exist_for_every_script(self):
        docs = list((ROOT / "rules").glob("*.md")) + [ROOT / "README.md"]
        docs += list((ROOT / "skills").glob("*/SKILL.md")) + list((ROOT / "agents").glob("*.md"))
        help_cache = {}
        for doc in docs:
            for line in doc.read_text().splitlines():
                for script in set(re.findall(r"scripts/(\w+)\.py", line)):
                    path = SCRIPTS / f"{script}.py"
                    if not path.exists():
                        self.fail(f"{doc.name} references missing script {script}.py")
                    if "argparse" not in path.read_text():
                        continue
                    if script not in help_cache:
                        res = subprocess.run([sys.executable, "-B", str(path), "--help"],
                                             capture_output=True, text=True, timeout=60)
                        help_cache[script] = set(re.findall(r"--[a-z][a-z0-9-]*", res.stdout))
                    for flag in re.findall(r"(?<![\w-])--[a-z][a-z0-9-]*", line.split(f"{script}.py", 1)[-1]):
                        self.assertIn(flag, help_cache[script], f"{doc.name}: {script}.py {flag}")


class PortabilityTests(unittest.TestCase):
    """The scripts must keep working on Python 3.10 (the oldest CI version)."""

    def test_no_backslash_inside_fstring_expressions(self):
        # A backslash inside the {...} of an f-string is a SyntaxError before Python 3.12.
        import ast
        for path in sorted(SCRIPTS.glob("*.py")):
            src = path.read_text()
            for node in ast.walk(ast.parse(src)):
                if isinstance(node, ast.FormattedValue):
                    segment = ast.get_source_segment(src, node.value) or ""
                    self.assertNotIn("\\", segment, f"{path.name}:{node.lineno}: {segment!r}")


