"""Tests for the C/C++ -> Python transpiler and the cppBridge CLI.

Run (from the plugin root):  python3 -B -m unittest discover -s tests -v

Reference values are either exact integer results of the C semantics (stated per test) or an
independent NumPy implementation of the same algorithm. Tolerances are stated per test; none were
loosened to make a test pass.
"""

import contextlib
